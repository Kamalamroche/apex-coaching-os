/* Rebuilds the movement library from supabase/library/apex-movement-library.csv
   (an export of Kamal's APEX-Movement-Library.xlsx).
   Writes packages/core/src/data/movementLibrary.ts and supabase/seed.sql.
   Run: node scripts/build-movement-library.ts  (Node 22.18+ runs TypeScript directly) */

import { readFileSync, writeFileSync } from "node:fs";
import { STARTER_EXERCISES } from "../packages/core/src/data/starterExercises.ts";
import { importSheet, type SheetRow } from "../packages/core/src/movementImport.ts";
import type { Exercise } from "../packages/core/src/types.ts";

const root = new URL("../", import.meta.url);
const read = (p: string) => readFileSync(new URL(p, root), "utf8");
const write = (p: string, s: string) => writeFileSync(new URL(p, root), s);

/* The sheet export has no embedded newlines, but names can be quoted and contain commas. */
function parseCsvLine(line: string): string[] {
  const out: string[] = [];
  let cur = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { out.push(cur); cur = ""; }
    else cur += c;
  }
  out.push(cur);
  return out;
}

const [, ...lines] = read("supabase/library/apex-movement-library.csv").trim().split("\n");
const rows: SheetRow[] = lines.map((line) => {
  const [no, category, name, equipment, focus] = parseCsvLine(line);
  return { no: Number(no), category: category!, name: name!.trim(), equipment: equipment!, focus: focus! };
});

const firstId = Math.max(...STARTER_EXERCISES.map((e) => e.id)) + 1;
const library = importSheet(rows, firstId);

/* ───────────── TypeScript ───────────── */

const ts = (v: unknown) => JSON.stringify(v).replace(/","/g, '", "');
const tsLine = (e: Exercise) =>
  `  { id: ${e.id}, name: ${ts(e.name)}, aliases: ${ts(e.aliases)}, pattern: ${ts(e.pattern)}, category: ${ts(e.category)}, equipment: ${ts(e.equipment)}, muscles: ${ts(e.muscles)}, cues: [], commonMistake: "", type: ${ts(e.type)}, focus: ${ts(e.focus)} },`;

write("packages/core/src/data/movementLibrary.ts", `import type { Exercise } from "../types";

/* Generated by scripts/build-movement-library.ts from the APEX Movement Library sheet. Do not edit by hand.
   Pattern, body area, muscles and some equipment are worked out from each name (see movementImport.ts).
   Cues and common mistakes are left empty for coaches to write. */
export const MOVEMENT_LIBRARY: Exercise[] = [
${library.map(tsLine).join("\n")}
];
`);

/* ───────────── SQL ───────────── */

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(", ")}]` : "'{}'::text[]");
const sqlRow = (e: Exercise) =>
  `  (${e.id}, ${q(e.name)}, ${arr(e.aliases)}, ${q(e.pattern.toLowerCase())}, ${q(e.category)}, ${q(e.equipment)}, ${arr(e.muscles)}, ${arr(e.cues)}, ${e.commonMistake ? q(e.commonMistake) : "null"}, ${q(e.type)}, ${q(e.focus)})`;

const all = [...STARTER_EXERCISES, ...library];
write("supabase/seed.sql", `-- Shared APEX movement library (owner_coach_id null): ${all.length} movements.
-- Generated by scripts/build-movement-library.ts. Do not edit by hand.
-- Ids are fixed so they match packages/core; ids 1-15 are the original starter movements.
-- Safe to run more than once: existing rows are updated, nothing is deleted.
-- Needs migration 20261026120000_movement_library.sql first.

do $$ begin
  if exists (select 1 from public.exercises where id between ${firstId} and ${all.at(-1)!.id} and owner_coach_id is not null) then
    raise exception 'A custom exercise already uses a library id (${firstId}-${all.at(-1)!.id}), so the ids would clash. Nothing was changed.';
  end if;
end $$;

insert into public.exercises (id, name, aliases, pattern, body_area, equipment, muscles, cues, common_mistake, training_type, focus)
overriding system value values
${all.map(sqlRow).join(",\n")}
on conflict (id) do update set
  name = excluded.name, aliases = excluded.aliases, pattern = excluded.pattern, body_area = excluded.body_area,
  equipment = excluded.equipment, muscles = excluded.muscles, cues = excluded.cues, common_mistake = excluded.common_mistake,
  training_type = excluded.training_type, focus = excluded.focus;

-- New custom exercises continue after the library.
select setval(pg_get_serial_sequence('public.exercises', 'id'), (select max(id) from public.exercises));
`);

console.log(`${library.length} sheet movements + ${STARTER_EXERCISES.length} starter = ${all.length}`);
